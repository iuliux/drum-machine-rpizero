// Function to send a command or data byte to the OLED
int send_byte(int fd, unsigned char mode, unsigned char data)
{
    unsigned char buffer[2] = {mode, data};
    if (write(fd, buffer, 2) != 2)
    {
        perror("Failed to send byte");
        return -1;
    }
    return 0;
}

// Function to initialize the SSD1306 OLED
int init_oled(int fd)
{
    unsigned char init_cmds[] = {
        0xAE,        // Display off
        0xD5, 0x80,  // Set display clock divide ratio/oscillator frequency
        0xA8, 0x3F,  // Set multiplex ratio (1 to 64)
        0xD3, 0x00,  // Set display offset
        0x40 | 0x00, // Set start line address
        0x8D, 0x14,  // Set Charge Pump (0x14 enable, 0x10 disable)
        0x20, 0x00,  // Set Memory Addressing Mode (0x02 Page, 0x00 Horizontal)
        0xA1,        // Set Segment Re-map (0xA1 column address 127 is mapped to SEG0)
        0xC8,        // Set COM Output Scan Direction (0xC8 remapped mode)
        0xDA, 0x12,  // Set COM Pins Hardware Configuration
        0x81, 0xCF,  // Set Contrast Control (0x81 is command, 0xCF is value)
        0xD9, 0xF1,  // Set Pre-charge Period
        0xDB, 0x40,  // Set VCOMH Deselect Level
        0xA4,        // Entire Display On (Resume from RAM content)
        0xA6,        // Set Normal Display (0xA6 normal, 0xA7 inverse)
        0x2E,        // Deactivate Scroll
        0xAF         // Display On
    };

    for (int i = 0; i < sizeof(init_cmds); i++)
    {
        if (send_byte(fd, COMMAND_MODE, init_cmds[i]) < 0)
            return -1;
    }
    return 0;
}

// Function to send the image data to the display
int draw_splash(int fd)
{
    // Set column address range
    send_byte(fd, COMMAND_MODE, 0x21);
    send_byte(fd, COMMAND_MODE, 0x00); // column start
    send_byte(fd, COMMAND_MODE, 0x7F); // column end (127)

    // Set page address range
    send_byte(fd, COMMAND_MODE, 0x22);
    send_byte(fd, COMMAND_MODE, 0x00); // page start (0)
    send_byte(fd, COMMAND_MODE, 0x07); // page end (7)

    for (int i = 0; i < IMAGE_SIZE; i++)
    {
        if (send_byte(fd, DATA_MODE, image_data[i]) < 0)
            return -1;
    }
    return 0;
}

int main()
{
    int fd;

    // Check data size (sanity check)
    if (sizeof(image_data) != IMAGE_SIZE)
    {
        fprintf(stderr, "Error: Image data size mismatch. Expected %d bytes, got %zu.\n", IMAGE_SIZE, sizeof(image_data));
        exit(EXIT_FAILURE);
    }

    // Open the I2C bus
    if ((fd = open(I2C_BUS, O_RDWR)) < 0)
    {
        perror("Failed to open I2C bus");
        exit(EXIT_FAILURE);
    }

    // Initiate I2C communication with the OLED address
    if (ioctl(fd, I2C_SLAVE, OLED_ADDR) < 0)
    {
        perror("Failed to acquire bus access and/or talk to slave");
        close(fd);
        exit(EXIT_FAILURE);
    }

    printf("Initializing OLED...\n");
    if (init_oled(fd) < 0)
    {
        close(fd);
        exit(EXIT_FAILURE);
    }

    printf("Drawing splash image...\n");
    if (draw_splash(fd) < 0)
    {
        close(fd);
        exit(EXIT_FAILURE);
    }

    printf("Done. Logo should be displayed.\n");
    close(fd);
    return 0;
}
